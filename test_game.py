from pathlib import Path
from playwright.sync_api import sync_playwright, expect
ROOT=Path(__file__).parent
with sync_playwright() as pw:
    browser = pw.chromium.launch(executable_path=__import__('os').environ.get('CHROMIUM_BIN'), args=['--no-sandbox','--disable-dev-shm-usage'])
    page=browser.new_page(viewport={'width':1280,'height':900},device_scale_factor=1,reduced_motion='reduce')
    errors, external=[], []
    page.on('pageerror',lambda exc:errors.append(str(exc)))
    page.on('request',lambda req:external.append(req.url) if req.url.startswith(('http:','https:')) else None)
    page.goto((ROOT/'game/index.html').resolve().as_uri())
    expect(page.locator('#clock')).to_have_text('01:30')
    expect(page.locator('.ticket')).to_have_count(3)
    expect(page.locator('#cook')).to_be_disabled()
    page.keyboard.press('1')
    page.get_by_role('button',name='2 Chili').click()
    page.keyboard.press('3')
    page.keyboard.press('q')
    expect(page.locator('#prepText')).to_have_text('1/2 chops')
    page.screenshot(path=str(ROOT/'screenshots/02-prep.jpg'),type='jpeg',quality=90)
    page.keyboard.press('q')
    page.keyboard.press('w')
    page.keyboard.press('e')
    expect(page.locator('#feedback')).to_contain_text('Not cooked yet')
    expect(page.locator('#heatLabel')).to_have_text('PLATE NOW',timeout=4200)
    page.screenshot(path=str(ROOT/'screenshots/03-wok.jpg'),type='jpeg',quality=90)
    page.keyboard.press('e')
    expect(page.locator('#plateText')).to_have_text('Mapo Moon Tofu')
    page.screenshot(path=str(ROOT/'screenshots/01-pass.jpg'),type='jpeg',quality=90)
    page.keyboard.press('Enter')
    expect(page.locator('.ticket.active')).to_contain_text('Lantern Noodles')
    assert int(page.locator('#score').inner_text())>=90
    for k in '125qqw': page.keyboard.press(k)
    expect(page.locator('#heatLabel')).to_have_text('PLATE NOW',timeout=4200)
    page.keyboard.press('e')
    page.keyboard.press('Enter')
    expect(page.locator('#feedback')).to_contain_text('Wrong ingredients')
    expect(page.locator('.ticket.active')).to_contain_text('Lantern Noodles')
    for k in '426qqw': page.keyboard.press(k)
    expect(page.locator('#heatLabel')).to_have_text('SCORCHED',timeout=5500)
    page.keyboard.press('x')
    expect(page.locator('#prepText')).to_have_text('0/3 ingredients')
    page.locator('#sound').click()
    expect(page.locator('#sound')).to_have_attribute('aria-pressed','true')
    page.clock.install()
    page.clock.fast_forward(91000)
    expect(page.locator('#result')).to_be_visible()
    page.locator('#playAgain').click()
    expect(page.locator('#clock')).to_have_text('01:30')
    expect(page.locator('#score')).to_have_text('000')
    page.clock.resume()
    phone=browser.new_page(viewport={'width':390,'height':844}, is_mobile=True,has_touch=True)
    phone.goto((ROOT/'game/index.html').resolve().as_uri())
    assert phone.evaluate('document.documentElement.scrollWidth') <= 390
    expect(phone.get_by_role('button',name='1 Tofu')).to_be_visible()
    assert not errors,errors
    assert not external,external
    print('PASS: play/serve/score, incorrect dishes, burning, reset, sound toggle, timeout/restart, mobile layout; no runtime errors or outbound requests.')
